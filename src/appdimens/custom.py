def _spec(spec):
    sid = spec["id"]
    return ScalingStrategy(sid, _read_config(spec, Config(), sid))


class BuiltInStrategies(object):
    SCALED = _spec({"id": "scaled"})
    POWER = _spec({"id": "power", "curve": {"type": "power", "exponent": 0.75}})
    LOGARITHMIC = _spec({"id": "logarithmic", "curve": {"type": "logarithmic", "k": 0.4}})
    INTERPOLATED = _spec({"id": "interpolated", "curve": {"type": "interpolated", "t": 0.5}})
    DIAGONAL = _spec({"id": "diagonal", "axis": "diagonal"})
    PERIMETER = _spec({"id": "perimeter", "axis": "perimeter"})
    FIXED = _spec({"id": "fixed", "curve": {"type": "constant", "factor": 1}})
    all = (SCALED, POWER, LOGARITHMIC, INTERPOLATED, DIAGONAL, PERIMETER, FIXED)

    @classmethod
    def by_name(cls, name):
        low = name.lower()
        for s in cls.all:
            if s.id.lower() == low:
                return s
        return None


