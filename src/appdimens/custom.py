class ResolvedScaling(object):
    """A strategy resolved for one screen: ``factor``, ``applied_rules`` and ``scale*``."""
    __slots__ = ("screen", "config", "factor", "applied_rules", "axis_dp", "reference_dp", "curve_factor",
                 "ar_multiplier", "multi_window_ignored", "_coef")

    def __init__(self, screen, config, factor, applied, axis_dp, ref_dp, curve_factor, ar_mul, mw_ignored=False):
        self.screen, self.config, self.factor, self.applied_rules = screen, config, factor, applied
        self.axis_dp, self.reference_dp, self.curve_factor = axis_dp, ref_dp, curve_factor
        self.ar_multiplier, self.multi_window_ignored = ar_mul, mw_ignored
        t = config.transform
        coef = math.nan
        if isinstance(t, _FormulaTransform) and t.expression.base_coefficient is not None:
            coef = t.expression.base_coefficient.evaluate(
                _variables(screen, self._ratio(), axis_dp, ref_dp, config.reference))
        self._coef = coef

    def _ratio(self):
        return self.axis_dp / self.reference_dp if self.reference_dp > 0 else 1.0

    def scale(self, base):
        """Layout value in dp."""
        base = float(base)
        out = base * self.factor
        c = self.config
        if (c.min_value is not None or c.max_value is not None) and out != 0:
            mag = abs(out)
            if c.min_value is not None and mag < c.min_value:
                mag = c.min_value
            if c.max_value is not None and mag > c.max_value:
                mag = c.max_value
            out = -mag if out < 0 else mag
        if self.multi_window_ignored:
            return out
        t = c.transform
        if t is None:
            return out
        if isinstance(t, _FormulaTransform):
            if t.proportional:
                return base * self._coef
            return t.expression.evaluate(_variables(self.screen, self._ratio(), self.axis_dp, self.reference_dp,
                                                    c.reference, base, out, self.factor))
        return float(t(base, out, self.screen))

    def effective_font_scale(self):
        return _font_effective(self.config.font_scale, self.screen.font_scale)

    def scale_sp_dp(self, base):
        """Text value in dp, font-scale policy applied (Android ``scaleSpDp``)."""
        return self.scale(base) * self.effective_font_scale()

    def scale_sp_units(self, base):
        """Text in sp units for toolkits that apply the system font scale themselves."""
        system = self.screen.font_scale
        corr = self.effective_font_scale() / system if system > 0 else 1.0
        return self.scale(base) * corr

    def explain(self, strategy_id):
        c = self.config
        f = lambda v: ("%.4f" % v).rstrip("0").rstrip(".")  # noqa: E731
        s = "[%s] %s %s=%sdp / ref %s = %s -> %r = %s" % (
            strategy_id, self.screen.device, c.axis, f(self.axis_dp), f(self.reference_dp),
            f(self.axis_dp / self.reference_dp) if self.reference_dp else "1", c.curve, f(self.curve_factor))
        if c.multiplier != 1:
            s += " x %s" % f(c.multiplier)
        if c.aspect_ratio:
            s += " x AR %s" % f(self.ar_multiplier)
        if c.min_factor is not None or c.max_factor is not None:
            s += " clamp[%s, %s]" % (f(c.min_factor) if c.min_factor is not None else "-",
                                     f(c.max_factor) if c.max_factor is not None else "-")
        s += " => factor %s" % f(self.factor)
        if c.transform is not None:
            s += " then %r" % (c.transform,) if isinstance(c.transform, _FormulaTransform) else " then transform"
        if self.applied_rules:
            s += " rules=%s" % list(self.applied_rules)
        return s


def _curve_factor(curve, ratio, axis_dp, ref_dp, reference, screen):
    k, v = curve.kind, curve.value
    if k == "linear":
        return ratio
    if k == "power":
        return _pow(ratio, v) if ratio > 0 else 0.0
    if k == "logarithmic":
        return 1.0 + v * math.log(ratio) if ratio > 0 else 1.0
    if k == "interpolated":
        return 1.0 + (ratio - 1.0) * v
    if k == "constant":
        return v
    if k == "breakpoints":
        pts = v
        if axis_dp <= pts[0][0]:
            return pts[0][1]
        for i in range(1, len(pts)):
            at, f = pts[i]
            if axis_dp <= at:
                a_at, a_f = pts[i - 1]
                span = at - a_at
                return f if span <= 0 else a_f + (f - a_f) * ((axis_dp - a_at) / span)
        return pts[-1][1]
    if k == "custom":
        return float(v(ratio, screen))
    return v.evaluate(_variables(screen, ratio, axis_dp, ref_dp, reference))


def resolve_scaling(config, screen):
    cfg = config
    applied = []
    for i, (cond, patch, name) in enumerate(config.rules):
        if cond.matches(screen):
            cfg = cfg.apply(patch)
            applied.append(name if name is not None else "#%d" % i)
    axis_dp = screen.read(cfg.axis)
    ref_dp = cfg.reference.read(cfg.axis)
    if cfg.ignore_multi_window and screen.multi_window:
        return ResolvedScaling(screen, cfg, 1.0, applied, axis_dp, ref_dp, 1.0, 1.0, True)
    ratio = axis_dp / ref_dp if ref_dp > 0 else 1.0
    cf = _curve_factor(cfg.curve, ratio, axis_dp, ref_dp, cfg.reference, screen)
    factor = cf * cfg.multiplier
    ar_mul = 1.0
    if cfg.aspect_ratio:
        k = cfg.sensitivity if cfg.sensitivity is not None else SENSITIVITY_DEFAULT
        ar_mul = 1.0 + k * math.log(screen.aspect_ratio / REFERENCE_ASPECT_RATIO)
        factor *= ar_mul
    if cfg.min_factor is not None and factor < cfg.min_factor:
        factor = cfg.min_factor
    if cfg.max_factor is not None and factor > cfg.max_factor:
        factor = cfg.max_factor
    if not math.isfinite(factor):
        raise ValueError("custom strategy produced a non-finite factor (%r)" % factor)
    return ResolvedScaling(screen, cfg, factor, tuple(applied), axis_dp, ref_dp, cf, ar_mul)


class ScalingStrategy(object):
    """A named, immutable strategy. ``dp``/``px``/``sp``/``sp_px`` take a value and an optional
    :class:`~appdimens.Dimens` scope, :class:`~appdimens.DimenMetrics` or :class:`ScreenSnapshot`."""

    def __init__(self, id, config):
        if not isinstance(id, str) or not id.strip():
            raise ValueError("strategy id must not be blank")
        self.id = id
        self.config = config.validate()
        self.value_dependent = config.value_dependent
        self._memo = None
        self._axis_variants = {}
        self._lock = threading.Lock()

    def resolve(self, target=None):
        """Memoized per snapshot. ``DimenMetrics`` snapshots are immutable, so the object itself is the
        memo token (one identity compare on the hot path, like Kotlin ``resolve(token, snapshot)``)."""
        if target is None:
            target = _default_scope()
        token = target if isinstance(target, ScreenSnapshot) else getattr(target, "metrics", target)
        m = self._memo
        if m is not None and m[0] is token:
            return m[1]
        screen = token if isinstance(token, ScreenSnapshot) else snapshot_from_metrics(token)
        if m is not None and isinstance(token, ScreenSnapshot) and m[2] == screen.key():
            r = m[1]
        else:
            r = resolve_scaling(self.config, screen)
        self._memo = (token, r, screen.key())
        return r

    def factor(self, target=None):
        return self.resolve(target).factor

    def dp(self, value, target=None):
        return self.resolve(target).scale(value)

    def px(self, value, target=None):
        r = self.resolve(target)
        return r.scale(value) * r.screen.density

    def sp(self, value, target=None):
        return self.resolve(target).scale_sp_dp(value)

    def sp_px(self, value, target=None):
        r = self.resolve(target)
        return r.scale_sp_dp(value) * r.screen.density

    def explain(self, target=None):
        return self.resolve(target).explain(self.id)

    def extend(self, id, spec=None, register=True):
        """Child strategy: ``spec`` is a JSON-style dict (same keys as the document)."""
        cfg = _read_config(dict(spec or {}), self.config, id)
        s = ScalingStrategy(id, cfg)
        if register:
            register_scaling_strategy(s)
        return s

    def with_axis(self, axis):
        axis = ScalingAxis.from_json(axis)
        if axis == self.config.axis:
            return self
        with self._lock:
            s = self._axis_variants.get(axis)
            if s is None:
                s = ScalingStrategy("%s@%s" % (self.id, axis), self.config.copy(axis=axis))
                self._axis_variants[axis] = s
        return s

    def to_json(self):
        return _json.dumps(_write_strategy(self.id, self.config), separators=(",", ":"))

    def __repr__(self):
        return "ScalingStrategy(%s)" % self.id


