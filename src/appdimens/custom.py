_registry = {}
_registry_lock = threading.Lock()
_default = [None]


def register_scaling_strategy(s):
    with _registry_lock:
        _registry[s.id] = s
    return s


def unregister_scaling_strategy(sid):
    with _registry_lock:
        _registry.pop(sid, None)


def get_scaling_strategy(sid):
    """Registered → built-in → preset (case-insensitive for the last two)."""
    return _registry.get(sid) or BuiltInStrategies.by_name(sid) or CustomPresets.by_name(sid)


def require_scaling_strategy(sid):
    s = get_scaling_strategy(sid)
    if s is None:
        raise ValueError("No scaling strategy '%s'. Registered: %s" % (sid, sorted(_registry)))
    return s


def registered_scaling_strategies():
    return dict(_registry)


def get_default_scaling_strategy():
    return _default[0] or BuiltInStrategies.SCALED


def set_default_scaling_strategy(s):
    _default[0] = None if s is None else pick_scaling_strategy(s)


def pick_scaling_strategy(s=None):
    """Instance, registered/built-in/preset id, text formula or ``None`` (the default)."""
    if s is None:
        return get_default_scaling_strategy()
    if isinstance(s, ScalingStrategy):
        return s
    if isinstance(s, str):
        found = get_scaling_strategy(s)
        return found if found is not None else scaling_formula(s)
    raise TypeError("expected a ScalingStrategy, an id or a formula")


def define_scaling_strategy(spec, register=True):
    """Builds a strategy from a JSON-style dict (``{"id": "brand", "extends": "power", ...}``)."""
    strategies, _ = decode_strategies({"strategies": [spec]})
    s = next(iter(strategies.values()))
    if register:
        register_scaling_strategy(s)
    return s


def load_scaling_strategies(text_or_obj):
    """Registers every strategy of a document (atomic) and applies its ``default``."""
    strategies, default_id = decode_strategies(text_or_obj)
    default = None
    if default_id is not None:
        default = strategies.get(default_id) or require_scaling_strategy(default_id)
    with _registry_lock:
        _registry.update(strategies)
    if default is not None:
        _default[0] = default
    return strategies


def export_scaling_strategies(strategies=None, default_id=None):
    items = list(strategies) if strategies is not None else list(_registry.values())
    doc = {"version": FORMAT_VERSION}
    if default_id is not None:
        doc["default"] = default_id
    doc["strategies"] = [_write_strategy(s.id, s.config) for s in items]
    return _json.dumps(doc, separators=(",", ":"))


def reset_for_test():
    with _registry_lock:
        _registry.clear()
    with _formulas_lock:
        _formulas.clear()
    _default[0] = None


