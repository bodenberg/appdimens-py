def _num(v, path):
    if v is None:
        return None
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        raise ValueError("%s must be a number" % path)
    if not math.isfinite(v):
        raise ValueError("%s must be finite" % path)
    return float(v)


def _bool(v, path):
    if v is None:
        return None
    if not isinstance(v, bool):
        raise ValueError("%s must be a boolean" % path)
    return v


def _obj(v, path):
    if v is None:
        return None
    if not isinstance(v, dict):
        raise ValueError("%s must be an object" % path)
    return v


def _list(v, path):
    if not isinstance(v, list):
        raise ValueError("%s must be an array" % path)
    return v


def _wrap(path, fn):
    try:
        return fn()
    except ValueError as e:
        raise ValueError("%s: %s" % (path, e))


def _read_curve(v, path):
    if isinstance(v, str):
        return _read_curve({"type": v}, path)
    if not isinstance(v, dict):
        raise ValueError("%s must be an object or string" % path)
    t = v.get("type")
    if not isinstance(t, str):
        raise ValueError("%s.type is required" % path)

    def nd(key, default):
        x = _num(v.get(key), "%s.%s" % (path, key))
        return default if x is None else x
    if t == "linear":
        return Curve.linear()
    if t == "power":
        return Curve.power(nd("exponent", 0.75))
    if t == "logarithmic":
        return Curve.logarithmic(nd("k", 0.4))
    if t == "interpolated":
        return Curve.interpolated(nd("t", 0.5))
    if t == "constant":
        return Curve.constant(nd("factor", 1.0))
    if t == "expression":
        src = v.get("expression")
        if not isinstance(src, str):
            raise ValueError("%s.expression is required" % path)
        return _wrap(path + ".expression", lambda: Curve.expression(src))
    if t == "breakpoints":
        pts = []
        for i, p in enumerate(_list(v.get("points"), path + ".points")):
            if not isinstance(p, dict):
                raise ValueError("%s.points[%d] must be an object" % (path, i))
            at = _num(p.get("at"), "%s.points[%d].at" % (path, i))
            f = _num(p.get("factor"), "%s.points[%d].factor" % (path, i))
            if at is None:
                raise ValueError("%s.points[%d].at is required" % (path, i))
            if f is None:
                raise ValueError("%s.points[%d].factor is required" % (path, i))
            pts.append((at, f))
        return Curve.breakpoints(pts)
    raise ValueError("%s.type '%s' is not one of linear, power, logarithmic, interpolated, constant, breakpoints, "
                     "expression" % (path, t))


def _read_font(v, path):
    if v == "follow":
        return FOLLOW
    if v == "ignore":
        return IGNORE
    if isinstance(v, dict):
        mx = _num(v.get("max"), path + ".max")
        if mx is None:
            raise ValueError("%s.max is required" % path)
        if mx <= 0:
            raise ValueError("fontScale max must be > 0")
        return ("clamp", mx)
    raise ValueError('%s must be "follow", "ignore" or {"max": n}' % path)


def _read_patch(o, path):
    clamp = _obj(o.get("clamp"), path + ".clamp")
    vclamp = _obj(o.get("valueClamp"), path + ".valueClamp")
    ar = o.get("aspectRatio")
    ref = o.get("reference")
    p = {}
    if isinstance(ref, dict):
        w = _num(ref.get("width"), path + ".reference.width")
        h = _num(ref.get("height"), path + ".reference.height")
        p["reference"] = ReferenceScreen(300.0 if w is None else w, 533.0 if h is None else h)
    if isinstance(o.get("axis"), str):
        p["axis"] = ScalingAxis.from_json(o["axis"])
    if o.get("curve") is not None:
        p["curve"] = _read_curve(o["curve"], path + ".curve")
    p["multiplier"] = _num(o.get("multiplier"), path + ".multiplier")
    p["min_factor"] = _num(clamp.get("min"), path + ".clamp.min") if clamp else None
    p["max_factor"] = _num(clamp.get("max"), path + ".clamp.max") if clamp else None
    p["min_value"] = _num(vclamp.get("min"), path + ".valueClamp.min") if vclamp else None
    p["max_value"] = _num(vclamp.get("max"), path + ".valueClamp.max") if vclamp else None
    if ar is None:
        p["aspect_ratio"] = None
    elif isinstance(ar, bool):
        p["aspect_ratio"] = ar
    elif isinstance(ar, dict):
        en = _bool(ar.get("enabled"), path + ".aspectRatio.enabled")
        p["aspect_ratio"] = True if en is None else en
    else:
        raise ValueError("%s.aspectRatio must be a boolean or object" % path)
    sens = _num(ar.get("sensitivity"), path + ".aspectRatio.sensitivity") if isinstance(ar, dict) else None
    p["sensitivity"] = sens if sens is not None else _num(o.get("sensitivity"), path + ".sensitivity")
    if o.get("fontScale") is not None:
        p["font_scale"] = _read_font(o["fontScale"], path + ".fontScale")
    p["ignore_multi_window"] = _bool(o.get("ignoreMultiWindow"), path + ".ignoreMultiWindow")
    f = o.get("formula")
    if f is not None:
        if not isinstance(f, str):
            raise ValueError("%s.formula must be a string" % path)
        p["transform"] = _wrap(path + ".formula", lambda: _FormulaTransform(f))
    return {k: v for k, v in p.items() if v is not None}


def _read_condition(o, path):
    def rng(key):
        r = o.get(key)
        if r is None:
            return (None, None)
        if not isinstance(r, dict):
            raise ValueError("%s.%s must be an object with min/max" % (path, key))
        return (_num(r.get("min"), "%s.%s.min" % (path, key)), _num(r.get("max"), "%s.%s.max" % (path, key)))
    d = o.get("device")
    if d is None:
        devices = None
    elif isinstance(d, str):
        devices = [DeviceClass.from_json(d)]
    elif isinstance(d, list):
        devices = []
        for x in d:
            if not isinstance(x, str):
                raise ValueError("%s.device entries must be strings" % path)
            devices.append(DeviceClass.from_json(x))
    else:
        raise ValueError("%s.device must be a string or array" % path)
    ori = o.get("orientation")
    if ori is not None and ori not in ("portrait", "landscape"):
        raise ValueError("%s.orientation '%s' must be portrait or landscape" % (path, ori))
    return Condition(devices, ori, rng("smallestWidth"), rng("width"), rng("height"), rng("aspectRatio"),
                     _bool(o.get("multiWindow"), path + ".multiWindow"))


def _read_config(o, parent, path):
    cfg = parent.apply(_read_patch(o, path))
    kw = {}
    if "clamp" in o and o["clamp"] is None:
        kw.update(min_factor=None, max_factor=None)
    if "valueClamp" in o and o["valueClamp"] is None:
        kw.update(min_value=None, max_value=None)
    if "formula" in o and o["formula"] is None:
        kw.update(transform=None)
    rules = []
    raw_rules = o.get("rules")
    for i, r in enumerate(_list(raw_rules, path + ".rules") if raw_rules is not None else []):
        if not isinstance(r, dict):
            raise ValueError("%s.rules[%d] must be an object" % (path, i))
        rp = "%s.rules[%d]" % (path, i)
        cond = _read_condition(_obj(r.get("when"), rp + ".when") or {}, rp + ".when")
        sset = _obj(r.get("set"), rp + ".set")
        if sset is None:
            raise ValueError("%s.set is required" % rp)
        name = r.get("name") if isinstance(r.get("name"), str) else None
        rules.append((cond, _read_patch(sset, rp + ".set"), name))
    kw["rules"] = tuple(parent.rules) + tuple(rules)
    return cfg.copy(**kw)


def decode_strategies(text_or_obj, lookup=None):
    """Parses a document → ``(strategies: dict, default_id)`` without registering anything."""
    root = _json.loads(text_or_obj) if isinstance(text_or_obj, str) else text_or_obj
    lookup = lookup or get_scaling_strategy
    default_id = None
    if isinstance(root, dict):
        if "strategies" in root:
            version = root.get("version")
            version = int(version) if isinstance(version, (int, float)) and not isinstance(version, bool) else FORMAT_VERSION
            if version > FORMAT_VERSION:
                raise ValueError("Unsupported strategies format version %d" % version)
            items = _list(root["strategies"], "strategies")
            default_id = root.get("default") if isinstance(root.get("default"), str) else None
        else:
            items = [root]
    elif isinstance(root, list):
        items = root
    else:
        raise ValueError("Expected a JSON object or array")
    raw = {}
    order = []
    for i, it in enumerate(items):
        if not isinstance(it, dict):
            raise ValueError("strategies[%d] must be an object" % i)
        sid = it.get("id")
        if not isinstance(sid, str):
            raise ValueError("strategies[%d].id is required" % i)
        if sid in raw:
            raise ValueError("Duplicate strategy id '%s'" % sid)
        raw[sid] = it
        order.append(sid)
    built = {}

    def build(sid, stack):
        if sid in built:
            return built[sid]
        if sid in stack:
            raise ValueError("Cyclic 'extends': %s" % " → ".join(stack + [sid]))
        o = raw[sid]
        pid = o.get("extends") if isinstance(o.get("extends"), str) else None
        if pid is None:
            parent = Config()
        elif pid in raw:
            parent = build(pid, stack + [sid]).config
        else:
            ps = lookup(pid)
            if ps is None:
                raise ValueError("'%s' extends unknown strategy '%s'" % (sid, pid))
            parent = ps.config
        s = ScalingStrategy(sid, _read_config(o, parent, sid))
        built[sid] = s
        return s
    for sid in order:
        build(sid, [])
    return {sid: built[sid] for sid in order}, default_id


def _n(v):
    return int(v) if float(v).is_integer() else v


def _write_curve(c):
    k = c.kind
    if k == "linear":
        return {"type": "linear"}
    if k == "power":
        return {"type": "power", "exponent": _n(c.value)}
    if k == "logarithmic":
        return {"type": "logarithmic", "k": _n(c.value)}
    if k == "interpolated":
        return {"type": "interpolated", "t": _n(c.value)}
    if k == "constant":
        return {"type": "constant", "factor": _n(c.value)}
    if k == "breakpoints":
        return {"type": "breakpoints", "points": [{"at": _n(a), "factor": _n(f)} for a, f in c.value]}
    if k == "expression":
        return {"type": "expression", "expression": c.value.source}
    raise ValueError("Custom curve lambdas cannot be encoded to JSON")


def _write_patch(p, defaults):
    out = {}
    t = p.get("transform")
    if t is not None and not isinstance(t, _FormulaTransform):
        raise ValueError("ValueTransform lambdas cannot be encoded to JSON")
    ref = p.get("reference")
    if ref is not None and (not defaults or ref != DEFAULT_REFERENCE):
        out["reference"] = {"width": _n(ref.width), "height": _n(ref.height)}
    if p.get("axis") is not None and (not defaults or p["axis"] != ScalingAxis.SMALLEST_WIDTH):
        out["axis"] = p["axis"]
    if p.get("curve") is not None:
        out["curve"] = _write_curve(p["curve"])
    if p.get("multiplier") is not None and (not defaults or p["multiplier"] != 1):
        out["multiplier"] = _n(p["multiplier"])
    for key, lo, hi in (("clamp", "min_factor", "max_factor"), ("valueClamp", "min_value", "max_value")):
        if p.get(lo) is not None or p.get(hi) is not None:
            out[key] = {k: _n(p[f]) for k, f in (("min", lo), ("max", hi)) if p.get(f) is not None}
    ar, sens = p.get("aspect_ratio"), p.get("sensitivity")
    if ar is not None and (not defaults or ar or sens is not None):
        out["aspectRatio"] = {"enabled": ar}
        if sens is not None:
            out["aspectRatio"]["sensitivity"] = _n(sens)
    elif ar is None and sens is not None:
        out["sensitivity"] = _n(sens)
    fs = p.get("font_scale")
    if fs is not None and (not defaults or fs != FOLLOW):
        out["fontScale"] = fs[0] if fs[0] != "clamp" else {"max": _n(fs[1])}
    if p.get("ignore_multi_window") is not None and (not defaults or p["ignore_multi_window"]):
        out["ignoreMultiWindow"] = p["ignore_multi_window"]
    if isinstance(t, _FormulaTransform):
        out["formula"] = t.expression.source
    return out


def _write_condition(c):
    out = {}
    if c.devices is not None:
        out["device"] = [d for d in DeviceClass.ALL if d in c.devices]
    if c.orientation is not None:
        out["orientation"] = c.orientation
    for key, (lo, hi) in (("smallestWidth", c.sw), ("width", c.w), ("height", c.h), ("aspectRatio", c.ar)):
        if lo is not None or hi is not None:
            out[key] = {k: _n(v) for k, v in (("min", lo), ("max", hi)) if v is not None}
    if c.multi_window is not None:
        out["multiWindow"] = c.multi_window
    return out


def _write_strategy(sid, c):
    out = {"id": sid}
    out.update(_write_patch({f: getattr(c, f) for f in _FIELDS}, True))
    if c.rules:
        rules = []
        for cond, patch, name in c.rules:
            r = {}
            if name is not None:
                r["name"] = name
            r["when"] = _write_condition(cond)
            r["set"] = _write_patch(patch, False)
            rules.append(r)
        out["rules"] = rules
    return out


