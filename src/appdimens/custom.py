_formulas = {}
_formulas_lock = threading.Lock()
MAX_SHARED_FORMULAS = 256


def scaling_formula(formula, id=None, register=None):
    """A strategy that computes the final value: text (``"base * pow(sw / 360, 0.8)"``) or
    code (``lambda f: f.base * f.pow(f.sw / 360, 0.8)`` with a :class:`FormulaScope`)."""
    reg = register if register is not None else id is not None
    if isinstance(formula, str):
        if id is None and not reg:
            with _formulas_lock:
                s = _formulas.get(formula)
                if s is None:
                    s = ScalingStrategy("formula:" + formula, Config(transform=_FormulaTransform(formula)))
                    if len(_formulas) < MAX_SHARED_FORMULAS:
                        _formulas[formula] = s
            return s
        s = ScalingStrategy(id or "formula:" + formula, Config(transform=_FormulaTransform(formula)))
    else:
        fn = formula
        s = ScalingStrategy(id or _next_lambda_id("formula"),
                            Config(transform=lambda base, _scaled, screen: fn(FormulaScope(screen, base))))
    if reg:
        register_scaling_strategy(s)
    return s


