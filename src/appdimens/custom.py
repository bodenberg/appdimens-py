def _finite(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v)


class ScalingAxis(object):
    SMALLEST_WIDTH = "smallestWidth"
    WIDTH = "width"
    HEIGHT = "height"
    MIN = "min"
    MAX = "max"
    DIAGONAL = "diagonal"
    PERIMETER = "perimeter"
    ALL = ("smallestWidth", "width", "height", "min", "max", "diagonal", "perimeter")
    _ALIASES = {"smallest_width": "smallestWidth", "smallestwidth": "smallestWidth"}

    @classmethod
    def from_json(cls, name):
        if isinstance(name, str):
            low = name.lower()
            for a in cls.ALL:
                if a.lower() == low:
                    return a
            if low in cls._ALIASES:
                return cls._ALIASES[low]
        raise ValueError("Unknown axis '%s'. Expected one of %s" % (name, list(cls.ALL)))


class DeviceClass(object):
    PHONE = "phone"
    TABLET = "tablet"
    DESKTOP = "desktop"
    TV = "tv"
    WATCH = "watch"
    CAR = "car"
    VR = "vr"
    ALL = ("phone", "tablet", "desktop", "tv", "watch", "car", "vr")

    @classmethod
    def from_json(cls, name):
        if isinstance(name, str) and name.lower() in cls.ALL:
            return name.lower()
        raise ValueError("Unknown device '%s'. Expected one of %s" % (name, list(cls.ALL)))

    @classmethod
    def from_ui_mode(cls, ui_mode, smallest_width):
        return {UiModeType.DESK: cls.DESKTOP, UiModeType.CAR: cls.CAR, UiModeType.TELEVISION: cls.TV,
                UiModeType.WATCH: cls.WATCH, UiModeType.VR_HEADSET: cls.VR}.get(
            ui_mode, cls.TABLET if smallest_width >= TABLET_MIN_SMALLEST_WIDTH_DP else cls.PHONE)


class ScreenSnapshot(object):
    __slots__ = ("width", "height", "smallest_width", "density", "font_scale", "landscape", "multi_window",
                 "device")

    def __init__(self, width, height, smallest_width=None, density=1.0, font_scale=1.0, landscape=None,
                 multi_window=False, device=None):
        self.width = float(width)
        self.height = float(height)
        self.smallest_width = float(min(width, height) if smallest_width is None else smallest_width)
        self.density = float(density)
        self.font_scale = float(font_scale)
        self.landscape = (self.width > self.height) if landscape is None else bool(landscape)
        self.multi_window = bool(multi_window)
        self.device = device or (DeviceClass.TABLET if self.smallest_width >= TABLET_MIN_SMALLEST_WIDTH_DP
                                 else DeviceClass.PHONE)

    @property
    def min_dp(self):
        return min(self.width, self.height)

    @property
    def max_dp(self):
        return max(self.width, self.height)

    @property
    def aspect_ratio(self):
        mn = self.min_dp
        return self.max_dp / mn if mn > 0 else 1.0

    def read(self, axis):
        if axis == ScalingAxis.SMALLEST_WIDTH:
            return self.smallest_width
        if axis == ScalingAxis.WIDTH:
            return self.width
        if axis == ScalingAxis.HEIGHT:
            return self.height
        if axis == ScalingAxis.MIN:
            return self.min_dp
        if axis == ScalingAxis.MAX:
            return self.max_dp
        if axis == ScalingAxis.DIAGONAL:
            return math.sqrt(self.min_dp ** 2 + self.max_dp ** 2)
        return self.min_dp + self.max_dp

    def key(self):
        return (self.width, self.height, self.smallest_width, self.density, self.font_scale, self.landscape,
                self.multi_window, self.device)


def snapshot_from_metrics(m):
    """:class:`~appdimens.DimenMetrics` → :class:`ScreenSnapshot` (device from the UI mode, Android rules)."""
    return ScreenSnapshot(m.width, m.height, m.smallest_width, m.density, m.font_scale, m.is_landscape,
                          m.multi_window, DeviceClass.from_ui_mode(m.ui_mode, m.smallest_width))


class ReferenceScreen(object):
    __slots__ = ("width", "height")

    def __init__(self, width=300.0, height=533.0):
        if not (_finite(width) and width > 0):
            raise ValueError("reference width must be > 0")
        if not (_finite(height) and height > 0):
            raise ValueError("reference height must be > 0")
        self.width, self.height = float(width), float(height)

    def read(self, axis):
        if axis in (ScalingAxis.SMALLEST_WIDTH, ScalingAxis.MIN):
            return min(self.width, self.height)
        if axis == ScalingAxis.WIDTH:
            return self.width
        if axis == ScalingAxis.HEIGHT:
            return self.height
        if axis == ScalingAxis.MAX:
            return max(self.width, self.height)
        if axis == ScalingAxis.DIAGONAL:
            return math.sqrt(self.width ** 2 + self.height ** 2)
        return self.width + self.height

    def __eq__(self, o):
        return isinstance(o, ReferenceScreen) and (o.width, o.height) == (self.width, self.height)

    def __hash__(self):
        return hash((self.width, self.height))


