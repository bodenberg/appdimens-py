def _font_effective(policy, system):
    kind, mx = policy
    if kind == "follow":
        return system
    if kind == "ignore":
        return 1.0
    return min(system, mx)


class Condition(object):
    __slots__ = ("devices", "orientation", "sw", "w", "h", "ar", "multi_window")

    def __init__(self, devices=None, orientation=None, sw=(None, None), w=(None, None), h=(None, None),
                 ar=(None, None), multi_window=None):
        self.devices = frozenset(devices) if devices is not None else None
        self.orientation, self.sw, self.w, self.h, self.ar, self.multi_window = orientation, sw, w, h, ar, multi_window

    def matches(self, s):
        if self.devices is not None and s.device not in self.devices:
            return False
        if self.orientation == "landscape" and not s.landscape:
            return False
        if self.orientation == "portrait" and s.landscape:
            return False
        for v, (lo, hi) in ((s.smallest_width, self.sw), (s.width, self.w), (s.height, self.h),
                            (s.aspect_ratio, self.ar)):
            if (lo is not None and v < lo) or (hi is not None and v >= hi):
                return False
        if self.multi_window is not None and s.multi_window != self.multi_window:
            return False
        return True


