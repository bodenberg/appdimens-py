class Curve(object):
    """``kind`` ∈ linear, power(exponent), logarithmic(k), interpolated(t), constant(factor),
    breakpoints(points), expression(expr), custom(fn(ratio, screen))."""
    __slots__ = ("kind", "value")

    def __init__(self, kind, value=None):
        self.kind, self.value = kind, value

    def __eq__(self, o):
        return isinstance(o, Curve) and o.kind == self.kind and o.value == self.value

    def __hash__(self):
        return hash((self.kind, str(self.value)))

    def __repr__(self):
        return "%s(%s)" % (self.kind, self.value if self.kind != "expression" else self.value.source)

    @staticmethod
    def linear():
        return Curve("linear")

    @staticmethod
    def power(exponent=0.75):
        return Curve("power", float(exponent))

    @staticmethod
    def logarithmic(k=0.4):
        return Curve("logarithmic", float(k))

    @staticmethod
    def interpolated(t=0.5):
        return Curve("interpolated", float(t))

    @staticmethod
    def constant(factor=1.0):
        return Curve("constant", float(factor))

    @staticmethod
    def breakpoints(points):
        pts = sorted(((float(a), float(f)) for a, f in points), key=lambda p: p[0])
        if not pts:
            raise ValueError("breakpoints need at least one point")
        for a, f in pts:
            if not (math.isfinite(a) and a >= 0):
                raise ValueError("breakpoint 'at' must be finite and >= 0")
            if not math.isfinite(f):
                raise ValueError("breakpoint factor must be finite")
        return Curve("breakpoints", tuple(pts))

    @staticmethod
    def expression(source):
        return Curve("expression", ScalingExpression.parse(source, CURVE_VARIABLES))


