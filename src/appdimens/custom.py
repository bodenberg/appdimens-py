def _pow(x, y):
    try:
        r = math.pow(x, y)
    except (ValueError, ZeroDivisionError):
        return math.inf if x == 0 else math.nan
    except OverflowError:
        return math.inf
    return r


def _safe(fn):
    def g(x):
        try:
            return fn(x)
        except (ValueError, OverflowError):
            if fn in (math.log, math.log10, math.log2):
                return -math.inf if x == 0 else math.nan
            if fn is math.exp:
                return math.inf
            return math.nan
    return g


def _div(x, y):
    if y == 0:
        if x == 0 or math.isnan(x):
            return math.nan
        return math.copysign(math.inf, x) * (math.copysign(1.0, y))
    return x / y


def _mod(x, y):
    if y == 0 or math.isinf(x):
        return math.nan
    return math.fmod(x, y)


def _smooth(a, b, x):
    t = _div(x - a, b - a)
    t = 0.0 if t < 0 else (1.0 if t > 1 else t)
    return t * t * (3 - 2 * t)


_FUNCS = {
    "min": lambda *a: min(a), "max": lambda *a: max(a), "clamp": lambda x, lo, hi: max(lo, min(hi, x)),
    "pow": _pow, "sqrt": _safe(math.sqrt), "ln": _safe(math.log), "log": _safe(math.log),
    "log10": _safe(math.log10), "log2": _safe(math.log2), "exp": _safe(math.exp), "abs": abs,
    "sign": lambda x: math.nan if x != x else (0.0 if x == 0 else math.copysign(1.0, x)),
    "floor": lambda x: float(math.floor(x)) if math.isfinite(x) else x,
    "ceil": lambda x: float(math.ceil(x)) if math.isfinite(x) else x,
    "round": lambda x: float(math.floor(x + 0.5)) if math.isfinite(x) else x,
    "lerp": lambda a, b, t: a + (b - a) * t, "step": lambda edge, x: 0.0 if x < edge else 1.0,
    "smoothstep": _smooth,
}


class _Node(object):
    __slots__ = ("kind", "val", "args")

    def __init__(self, kind, val=None, args=()):
        self.kind, self.val, self.args = kind, val, args

    def reads(self, names):
        if self.kind == "var":
            return self.val in names
        return any(a.reads(names) for a in self.args)

    def compile(self):
        k = self.kind
        if k == "num":
            v = self.val
            return lambda env: v
        if k == "var":
            name = self.val
            return lambda env: env(name)
        fs = [a.compile() for a in self.args]
        if k == "neg":
            a, = fs
            return lambda env: -a(env)
        if k == "not":
            a, = fs
            return lambda env: 0.0 if a(env) != 0 else 1.0
        if k == "ternary":
            c, a, b = fs
            return lambda env: a(env) if c(env) != 0 else b(env)
        if k == "call":
            fn = _FUNCS[self.val]
            return lambda env: fn(*[f(env) for f in fs])
        a, b = fs
        op = self.val
        if op == "&&":
            return lambda env: 1.0 if (a(env) != 0 and b(env) != 0) else 0.0
        if op == "||":
            return lambda env: 1.0 if (a(env) != 0 or b(env) != 0) else 0.0
        ops = {"+": lambda x, y: x + y, "-": lambda x, y: x - y, "*": lambda x, y: x * y, "/": _div,
               "%": _mod, "^": _pow, "==": lambda x, y: 1.0 if x == y else 0.0,
               "!=": lambda x, y: 1.0 if x != y else 0.0, "<": lambda x, y: 1.0 if x < y else 0.0,
               "<=": lambda x, y: 1.0 if x <= y else 0.0, ">": lambda x, y: 1.0 if x > y else 0.0,
               ">=": lambda x, y: 1.0 if x >= y else 0.0}
        f = ops[op]
        return lambda env: f(a(env), b(env))


class _Parser(object):
    def __init__(self, src, allowed):
        self.src, self.allowed, self.i = src, allowed, 0

    def fail(self, msg):
        raise ValueError('Invalid expression at %d: %s in "%s"' % (self.i, msg, self.src))

    def ws(self):
        while self.i < len(self.src) and self.src[self.i].isspace():
            self.i += 1

    def peek_is(self, tok):
        self.ws()
        return self.src.startswith(tok, self.i)

    def eat(self, tok):
        if not self.peek_is(tok):
            return False
        self.i += len(tok)
        return True

    def parse_all(self):
        if not self.src.strip():
            self.fail("empty expression")
        n = self.ternary()
        self.ws()
        if self.i < len(self.src):
            self.fail("unexpected '%s'" % self.src[self.i])
        return n

    def ternary(self):
        c = self.or_()
        if not self.eat("?"):
            return c
        a = self.ternary()
        if not self.eat(":"):
            self.fail("expected ':'")
        return _Node("ternary", None, (c, a, self.ternary()))

    def or_(self):
        n = self.and_()
        while self.eat("||"):
            n = _Node("bin", "||", (n, self.and_()))
        return n

    def and_(self):
        n = self.cmp()
        while self.eat("&&"):
            n = _Node("bin", "&&", (n, self.cmp()))
        return n

    def cmp(self):
        n = self.add()
        for op in ("==", "!=", "<=", ">=", "<", ">"):
            if self.eat(op):
                return _Node("bin", op, (n, self.add()))
        return n

    def add(self):
        n = self.mul()
        while True:
            if self.eat("+"):
                n = _Node("bin", "+", (n, self.mul()))
            elif self.eat("-"):
                n = _Node("bin", "-", (n, self.mul()))
            else:
                return n

    def mul(self):
        n = self.unary()
        while True:
            if self.eat("*"):
                n = _Node("bin", "*", (n, self.unary()))
            elif self.eat("/"):
                n = _Node("bin", "/", (n, self.unary()))
            elif self.eat("%"):
                n = _Node("bin", "%", (n, self.unary()))
            else:
                return n

    def unary(self):
        if self.eat("-"):
            return _Node("neg", None, (self.unary(),))
        if self.eat("+"):
            return self.unary()
        if self.peek_is("!") and not self.peek_is("!="):
            self.eat("!")
            return _Node("not", None, (self.unary(),))
        return self.power()

    def power(self):
        n = self.primary()
        if self.eat("^"):
            return _Node("bin", "^", (n, self.unary()))
        return n

    def primary(self):
        self.ws()
        s = self.src
        if self.i >= len(s):
            self.fail("unexpected end")
        c = s[self.i]
        if c == "(":
            self.i += 1
            n = self.ternary()
            if not self.eat(")"):
                self.fail("expected ')'")
            return n
        if c.isdigit() or c == ".":
            return self.number()
        if c.isalpha() or c == "_":
            start = self.i
            while self.i < len(s) and (s[self.i].isalnum() or s[self.i] == "_"):
                self.i += 1
            name = s[start:self.i]
            if self.eat("("):
                return self.call(name, start)
            if name == "true":
                return _Node("num", 1.0)
            if name == "false":
                return _Node("num", 0.0)
            if name not in self.allowed:
                self.i = start
                self.fail("unknown variable '%s' (allowed: %s)" % (name, ", ".join(sorted(self.allowed))))
            return _Node("var", name)
        self.fail("unexpected '%s'" % c)

    def call(self, name, start):
        args = []
        if not self.eat(")"):
            while True:
                args.append(self.ternary())
                if not self.eat(","):
                    break
            if not self.eat(")"):
                self.fail("expected ')'")
        arity = _ARITY.get(name)
        if arity is None:
            self.i = start
            self.fail("unknown function '%s'" % name)
        if not (arity[0] <= len(args) <= arity[1]):
            self.i = start
            self.fail("'%s' takes %s argument(s), got %d" % (
                name, str(arity[0]) if arity[0] == arity[1] else "%d+" % arity[0], len(args)))
        return _Node("call", name, tuple(args))

    def number(self):
        s, start = self.src, self.i
        while self.i < len(s) and (s[self.i].isdigit() or s[self.i] == "."):
            self.i += 1
        if self.i < len(s) and s[self.i] in "eE":
            save = self.i
            self.i += 1
            if self.i < len(s) and s[self.i] in "+-":
                self.i += 1
            if self.i < len(s) and s[self.i].isdigit():
                while self.i < len(s) and s[self.i].isdigit():
                    self.i += 1
            else:
                self.i = save
        text = s[start:self.i]
        try:
            return _Node("num", float(text))
        except ValueError:
            self.i = start
            self.fail("bad number '%s'" % text)


class ScalingExpression(object):
    """The shared text language: ``base * pow(sw / 360, 0.8)``, ``tablet ? 1.2 : 1``, ``clamp(ratio, 0.9, 1.5)``."""
    __slots__ = ("source", "_root", "_fn", "_coef")

    def __init__(self, source, root):
        self.source = source
        self._root = root
        self._fn = root.compile()
        self._coef = False

    @classmethod
    def parse(cls, source, allowed=FORMULA_VARIABLES):
        return cls(source, _Parser(source, allowed).parse_all())

    def evaluate(self, env):
        """``env`` maps a variable name to a float (callable) or is a dict."""
        if isinstance(env, dict):
            d = env
            return self._fn(lambda n: d.get(n, math.nan))
        return self._fn(env)

    @property
    def base_coefficient(self):
        """For ``base`` / ``base * X`` / ``X * base`` (X not reading base/scaled/factor): X, else None."""
        if self._coef is False:
            r = self._root
            c = None
            if r.kind == "var" and r.val == "base":
                c = ScalingExpression(self.source, _Node("num", 1.0))
            elif r.kind == "bin" and r.val == "*":
                a, b = r.args
                if a.kind == "var" and a.val == "base" and not b.reads(_VALUE_VARIABLES):
                    c = ScalingExpression(self.source, b)
                elif b.kind == "var" and b.val == "base" and not a.reads(_VALUE_VARIABLES):
                    c = ScalingExpression(self.source, a)
            self._coef = c
        return self._coef

    def __eq__(self, o):
        return isinstance(o, ScalingExpression) and o.source == self.source

    def __hash__(self):
        return hash(self.source)

    def __repr__(self):
        return self.source


def _variables(screen, ratio, axis_dp, ref_dp, reference, base=math.nan, scaled=math.nan, factor=math.nan):
    dev = screen.device
    table = {
        "sw": screen.smallest_width, "width": screen.width, "height": screen.height, "shortSide": screen.min_dp,
        "longSide": screen.max_dp, "diagonal": screen.read(ScalingAxis.DIAGONAL),
        "perimeter": screen.read(ScalingAxis.PERIMETER), "aspectRatio": screen.aspect_ratio,
        "density": screen.density, "fontScale": screen.font_scale, "landscape": 1.0 if screen.landscape else 0.0,
        "portrait": 0.0 if screen.landscape else 1.0, "multiWindow": 1.0 if screen.multi_window else 0.0,
        "pi": math.pi, "e": math.e, "ratio": ratio, "axis": axis_dp, "ref": ref_dp, "refWidth": reference.width,
        "refHeight": reference.height, "base": base, "scaled": scaled, "factor": factor,
    }
    for d in DeviceClass.ALL:
        table[d] = 1.0 if dev == d else 0.0
    return lambda n: table.get(n, math.nan)


