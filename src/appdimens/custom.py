def cdp(value, strategy=None, target=None):
    """Layout value in dp through a custom strategy (instance, id, text formula or default)."""
    return pick_scaling_strategy(strategy).dp(value, target)


def cdp_px(value, strategy=None, target=None):
    return pick_scaling_strategy(strategy).px(value, target)


def csp(value, strategy=None, target=None):
    """Text in dp, the strategy's font-scale policy applied."""
    return pick_scaling_strategy(strategy).sp(value, target)


def csp_px(value, strategy=None, target=None):
    return pick_scaling_strategy(strategy).sp_px(value, target)


def csp_units(value, strategy=None, target=None):
    """Text for toolkits that multiply by the system font scale themselves."""
    return pick_scaling_strategy(strategy).resolve(target).scale_sp_units(value)
